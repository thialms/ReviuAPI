CREATE TABLE users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(255) NOT NULL,
    username VARCHAR(255) NOT NULL,
    email VARCHAR(255) NOT NULL,
    password VARCHAR(255),
    verification_code VARCHAR(255),
    verified BOOLEAN,
    verification_expiry TIMESTAMP(6) WITH TIME ZONE,
    forgot_password_code VARCHAR(255),
    forgot_password_expiry TIMESTAMP(6) WITH TIME ZONE,
    CONSTRAINT uk_users_username UNIQUE (username),
    CONSTRAINT uk_users_email UNIQUE (email)
);

CREATE TABLE decks (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(255),
    user_id BIGINT,
    CONSTRAINT fk_decks_user
        FOREIGN KEY (user_id) REFERENCES users (id)
);

CREATE TABLE cards (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    front_text VARCHAR(255),
    back_text VARCHAR(255),
    image_url VARCHAR(255),
    audio_url VARCHAR(255),
    repetitions INTEGER NOT NULL,
    interval INTEGER NOT NULL,
    easiness_factor DOUBLE PRECISION NOT NULL,
    last_review DATE,
    next_review DATE,
    deck_id BIGINT,
    CONSTRAINT fk_cards_deck
        FOREIGN KEY (deck_id) REFERENCES decks (id)
);

CREATE INDEX idx_decks_user_id ON decks (user_id);
CREATE INDEX idx_cards_deck_id ON cards (deck_id);
