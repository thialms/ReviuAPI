ALTER TABLE users DROP COLUMN verification_code, DROP COLUMN verification_expiry, DROP COLUMN forgot_password_code,  DROP COLUMN forgot_password_expiry;

CREATE TABLE verification_codes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code VARCHAR(255),
    expiry TIMESTAMP(6) WITH TIME ZONE,
    user_id BIGINT NOT NULL,
    CONSTRAINT fk_verification_codes_user
        FOREIGN KEY (user_id) REFERENCES users (id)
);